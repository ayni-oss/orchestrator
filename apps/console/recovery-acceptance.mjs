// Canonical deployed recovery review, including accepted response loss and reload.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const endpoint = process.env.CONSOLE_URL;
assert.equal(new URL(endpoint).hostname, '127.0.0.1');
const coding = JSON.parse(await readFile(process.env.TASK_CONSOLE_SELECTION_FILE, 'utf8'));
const scope = { workspaceId: coding.scope.workspace, projectId: coding.scope.project, conversationId: coding.scope.conversation };
const evidence = process.env.TASK_CONSOLE_EVIDENCE_DIRECTORY;
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(scope => sessionStorage.setItem('selection', JSON.stringify(scope)), scope);
  const page = await context.newPage(); const errors = []; const starts = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', r => { if (/\/api\/(StartTaskExecution|StartTaskPublication|SendMessage)$/.test(r.url())) starts.push(r.url()); });
  const api = (method, body) => page.evaluate(async ({ method, body }) => {
    const response = await fetch(`/api/${method}`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Console-Request': '1' }, body: JSON.stringify(body) });
    if (!response.ok) throw new Error(`${method} failed`); return response.json();
  }, { method, body });
  await page.goto(endpoint);
  await page.locator('[data-inspect-task]').first().click();
  await page.locator('#task-auto-refresh').uncheck();
  await page.getByRole('button', { name: 'Record recovery proposal', exact: true }).waitFor();
  assert.match(await page.locator('#task-recovery').innerText(), /does not start work/);
  const task = (await api('ListTasks', { ...scope, limit: 20 })).tasks[0];
  const attemptId = (await api('GetTaskExecution', { ...scope, taskId: task.id })).preparation.attemptId;
  const selected = { ...scope, taskId: task.id, attemptId };
  const before = await api('GetTaskAttempt', selected);
  await page.getByLabel('Record recovery proposal', { exact: true }).fill('Inspect saved changes <script>unsafe()</script> before continuing.');
  await page.getByLabel('Additional seconds', { exact: true }).fill('180');
  await page.getByLabel('Additional tokens', { exact: true }).fill('2048');
  let accepted;
  await page.route('**/api/RecordTaskRecovery', async route => {
    const response = await route.fetch(); assert.equal(response.status(), 200);
    accepted = { request: route.request().postDataJSON(), response: await response.json() }; await route.abort('failed');
  }, { times: 1 });
  await page.getByRole('button', { name: 'Record recovery proposal', exact: true }).click();
  await page.locator('#pending').waitFor({ state: 'visible' });
  await page.waitForFunction(() => !document.querySelector('#retry').disabled);
  await page.reload(); await page.locator('#pending').waitFor({ state: 'visible' });
  const replay = page.waitForResponse(r => r.url().endsWith('/api/RecordTaskRecovery'));
  await page.locator('#retry').click(); const response = await replay;
  assert.equal(response.status(), 200); assert.deepEqual(response.request().postDataJSON(), accepted.request); assert.deepEqual(await response.json(), accepted.response);
  await page.locator(`[data-recovery-id="${accepted.response.record.id}"]`).waitFor();
  assert.equal(await page.locator('#task-recovery script').count(), 0);
  assert.match(await page.locator('#task-recovery').innerText(), /180 seconds and 2048 tokens/);
  await page.getByLabel('Record operator question', { exact: true }).fill('Preserve the accepted patch?');
  const questionResponse = page.waitForResponse(r => r.url().endsWith('/api/RecordTaskRecovery'));
  await page.getByRole('button', { name: 'Record operator question', exact: true }).click();
  const question = (await (await questionResponse).json()).record;
  const questionNode = page.locator(`[data-recovery-id="${question.id}"]`);
  const second = await context.newPage();
  await second.goto(endpoint);
  await second.locator('[data-inspect-task]').first().click();
  await second.locator('#task-auto-refresh').uncheck();
  const secondQuestion = second.locator(`[data-recovery-id="${question.id}"]`);
  await secondQuestion.getByLabel('Record answer', { exact: true }).fill('A competing answer must not replace the first.');
  await questionNode.getByLabel('Record answer', { exact: true }).fill('Preserve it and review the failed check.');
  await questionNode.getByRole('button', { name: 'Record answer', exact: true }).click();
  await page.waitForFunction(id => !document.querySelector(`[data-recovery-id="${id}"] form`), question.id);
  const conflict = second.waitForResponse(r => r.url().endsWith('/api/RecordTaskRecovery'));
  await secondQuestion.getByRole('button', { name: 'Record answer', exact: true }).click();
  assert.notEqual((await conflict).status(), 200);
  await second.waitForFunction(id => !document.querySelector(`[data-recovery-id="${id}"] form`), question.id);
  assert.match(await secondQuestion.innerText(), /Preserve it and review the failed check/);
  await page.reload(); await page.locator(`[data-recovery-id="${question.id}"]`).waitFor();
  assert.equal(await page.locator(`[data-recovery-id="${question.id}"] form`).count(), 0);
  assert.deepEqual(await api('GetTaskAttempt', selected), before);
  assert.equal((await api('ListTaskFeedback', { ...scope, limit: 32 })).feedback[0].state, 'open');
  let confirmation;
  if (process.env.TASK_RECOVERY_CONFIRM === 'true') {
    const article = page.locator(`[data-recovery-id="${accepted.response.record.id}"]`);
    const confirm = article.getByRole('button', { name: 'Confirm recovery', exact: true });
    assert.equal(await confirm.isDisabled(), true);
    await article.locator('[data-recovery-consent]').check();
    const secondArticle = second.locator(`[data-recovery-id="${accepted.response.record.id}"]`);
    await secondArticle.locator('[data-recovery-consent]').check();
    await page.route('**/api/ConfirmTaskRecovery', async route => {
      const response = await route.fetch(); assert.equal(response.status(), 200);
      confirmation = { request: route.request().postDataJSON(), response: await response.json() }; await route.abort('failed');
    }, { times: 1 });
    await confirm.click(); await page.locator('#pending').waitFor({ state: 'visible' });
    await page.waitForFunction(() => !document.querySelector('#retry').disabled);
    const secondReceipt = second.waitForResponse(r => r.url().endsWith('/api/ConfirmTaskRecovery'));
    await secondArticle.getByRole('button', { name: 'Confirm recovery', exact: true }).click();
    const raced = await secondReceipt; assert.equal(raced.status(), 200);
    assert.deepEqual(await raced.json(), confirmation.response);
    assert.notEqual(raced.request().postDataJSON().idempotencyKey, confirmation.request.idempotencyKey);
    const other = (await api('CreateConversation', { workspaceId: scope.workspaceId, projectId: scope.projectId, title: 'Recovery navigation boundary', idempotencyKey: crypto.randomUUID() })).conversation;
    await page.evaluate(selection => sessionStorage.setItem('selection', JSON.stringify(selection)), { ...scope, conversationId: other.id });
    await page.reload(); await page.locator('#pending').waitFor({ state: 'visible' });
    const replay = page.waitForResponse(r => r.url().endsWith('/api/ConfirmTaskRecovery'));
    await page.locator('#retry').click(); const response = await replay;
    assert.equal(response.status(), 200); assert.deepEqual(response.request().postDataJSON(), confirmation.request); assert.deepEqual(await response.json(), confirmation.response);
    assert.equal(await page.locator(`[data-recovery-id="${accepted.response.record.id}"]`).count(), 0);
    await page.evaluate(scope => sessionStorage.setItem('selection', JSON.stringify(scope)), scope);
    await page.reload();
    await page.locator(`[data-recovery-id="${accepted.response.record.id}"]`).getByRole('button', { name: 'Inspect continued attempt', exact: true }).click();
    const childId = confirmation.response.confirmation.attemptId;
    await page.waitForFunction(id => document.querySelector('#task-status')?.dataset.codingState === 'completed' && document.querySelector('#task-detail')?.textContent.includes(id), childId, { timeout: 180000 });
    const child = (await api('GetTaskAttempt', { ...selected, attemptId: childId })).attempt;
    assert.equal(child.parentAttemptId, attemptId); assert.equal(child.savedInputPatch, before.attempt.patch);
    assert.equal(child.maxSeconds, 180); assert.equal(child.maxTokens, 2048); assert.match(child.patch, /task-recovery-result.txt/);
    assert.deepEqual(await api('GetTaskAttempt', selected), before);
    await page.locator('#conversation-feedback-refresh').click();
    const notice = page.locator(`[data-recovery-outcome="${childId}"]`).first();
    await notice.waitFor(); assert.match(await notice.innerText(), /coding: completed/);
    const resolved = (await api('ListTaskFeedback', { ...scope, limit: 32 })).feedback.find(f => f.attemptId === attemptId);
    assert.equal(resolved.state, 'resolved'); assert.equal(resolved.recoveryAttemptId, childId);
    assert.equal(child.quality.state, 'failed');
    const childFeedback = (await api('ListTaskFeedback', { ...scope, limit: 32 })).feedback.find(f => f.attemptId === childId);
    assert.equal(childFeedback.state, 'open'); assert.equal(childFeedback.safeReason, 'quality_failed');
    assert.equal(await page.locator(`#project-attention-list [data-feedback-id="${resolved.id}"]`).count(), 0);
    await page.getByRole('button', { name: 'Inspect previous attempt', exact: true }).click();
    await page.locator(`[data-recovery-id="${accepted.response.record.id}"]`).getByRole('button', { name: 'Inspect continued attempt', exact: true }).waitFor();
    assert.equal(await page.locator(`[data-recovery-id="${accepted.response.record.id}"]`).getByRole('button', { name: 'Confirm recovery', exact: true }).count(), 0);
  }
  await second.close();
  assert.deepEqual(starts, []); assert.deepEqual(errors, []);
  await mkdir(evidence, { recursive: true });
  await page.screenshot({ path: `${evidence}/recovery-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: `${evidence}/recovery-mobile.png`, fullPage: true });
  await writeFile(`${evidence}/outcome.json`, JSON.stringify({ result: 'passed', scope, selected, accepted, question, confirmation, cases: ['canonical-proposal', 'saved-work', 'bounded-allowance', 'accepted-response-loss', 'exact-reload-retry', 'question-answer', 'two-tab-answer-conflict', 'two-tab-confirmation', 'pending-origin-after-navigation', 'continued-outcome', 'unchanged-attempt', 'attention-resolution', 'no-dispatch', 'escaped-text', 'mobile-layout'] }, null, 2));
  console.log(`deployed recovery review passed; evidence=${evidence}`);
} finally { await browser.close(); }

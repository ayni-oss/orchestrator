import {expect,test} from "@playwright/test";
test.beforeEach(async({request})=>{await request.post("http://127.0.0.1:50062/reset-project");});
test("workspace membership and archive retain project links, goals and task history",async({page})=>{
  await page.goto("/workspaces");
  await page.getByRole("button",{name:"Create workspace",exact:true}).click();
  await page.getByLabel("Workspace name",{exact:true}).fill("Shared engineering");
  await expect(page.getByLabel("Workspace name",{exact:true})).toHaveValue("Shared engineering");
  await page.getByRole("button",{name:"Repositories",exact:true}).click();
  await page.getByRole("checkbox",{name:"ayni-oss/sandbox",exact:true}).check();
  await page.getByRole("button",{name:"Done",exact:true}).click();
  await expect(page.getByRole("button",{name:"Done",exact:true})).toBeHidden();
  await expect(page.getByLabel("Workspace name",{exact:true})).toHaveValue("Shared engineering");
  await page.getByRole("dialog").getByRole("button",{name:"Create workspace",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Shared engineering",exact:true})).toBeVisible();
  await page.getByRole("navigation",{name:"Workspace views"}).getByRole("link",{name:"Settings",exact:true}).click();
  await page.getByLabel("Workspace name",{exact:true}).fill("Engineering workspace");
  await page.getByRole("button",{name:"Save workspace settings",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Engineering workspace",exact:true})).toBeVisible();
  await page.getByRole("navigation",{name:"Workspace views"}).getByRole("link",{name:"Projects",exact:true}).click();
  await expect(page.getByRole("link",{name:"Sandbox",exact:true})).toHaveAttribute("href","/projects/project%3A1");
  await expect(page.getByText("Improve the sandbox",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Create project",exact:true}).click();
  await expect(page.getByRole("dialog")).toContainText("Workspace: Engineering workspace");
  await expect(page.getByLabel("Workspace",{exact:true})).toHaveCount(0);
  await page.getByRole("button",{name:"Repositories",exact:true}).click();
  await expect(page.getByRole("checkbox",{name:"ayni-oss/sandbox",exact:true})).toBeVisible();
  await expect(page.getByRole("checkbox",{name:"ayni-oss/library",exact:true})).toHaveCount(0);
  await page.keyboard.press("Escape");await page.keyboard.press("Escape");
  await page.goto("/workspaces/workspace%3A1?view=settings");
  await page.getByRole("button",{name:"Archive workspace",exact:true}).click();
  await page.getByRole("dialog").getByRole("button",{name:"Archive workspace",exact:true}).click();
  await expect(page.getByText("New work is disabled. Existing tasks and project history are retained.",{exact:true})).toBeVisible();
  await page.getByRole("navigation",{name:"Workspace views"}).getByRole("link",{name:"Projects",exact:true}).click();
  await page.getByRole("link",{name:"Sandbox",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Sandbox",exact:true})).toBeVisible();
  await page.getByRole("navigation",{name:"Project views"}).getByRole("link",{name:"Tasks",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Tasks",exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"New task",exact:true})).toHaveCount(0);
  await expect(page.getByRole("button",{name:"New conversation",exact:true})).toHaveCount(0);
  await page.goto("/tasks");
  await expect(page.getByRole("heading",{name:"Task history",exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"Submit task",exact:true})).toHaveCount(0);
});

test("workspaces scope navigation, project creation, and existing repository membership",async({page})=>{
  await page.goto("/projects");
  await expect(page).toHaveURL(/\/workspaces$/);
  await expect(page.getByRole("link",{name:"Projects",exact:true})).toHaveCount(0);
  await expect(page.getByText("1 project · 2 repositories",{exact:true})).toBeVisible();
  await page.getByRole("link",{name:"Shared workspace",exact:true}).click();
  const views=page.getByRole("navigation",{name:"Workspace views"});
  await views.getByRole("link",{name:"Repositories",exact:true}).click();
  await expect(page.getByRole("button",{name:"Connect repository",exact:true})).toHaveCount(0);
  await page.getByLabel("Add or remove existing repositories",{exact:true}).click();
  await page.getByRole("checkbox",{name:"ayni-oss/library",exact:true}).uncheck();
  await page.getByRole("button",{name:"Done",exact:true}).click();
  await page.getByRole("button",{name:"Save repository membership",exact:true}).click();
  await expect(page.getByRole("link",{name:"ayni-oss/library",exact:true})).toHaveCount(0);
  await views.getByRole("link",{name:"Projects",exact:true}).click();
  await page.getByRole("button",{name:"Create project",exact:true}).click();
  await expect(page.getByRole("dialog")).toContainText("Workspace: Shared workspace");
  await page.getByRole("button",{name:"Repositories",exact:true}).click();
  await expect(page.getByRole("checkbox",{name:"ayni-oss/library",exact:true})).toHaveCount(0);
  await page.keyboard.press("Escape");await page.keyboard.press("Escape");
  await page.getByRole("link",{name:"Sandbox",exact:true}).click();
  await expect(page.getByRole("navigation",{name:"Breadcrumb"})).toContainText("Workspaces");
  await expect(page.getByRole("navigation",{name:"Breadcrumb"}).getByRole("link",{name:"Shared workspace",exact:true})).toBeVisible();
});

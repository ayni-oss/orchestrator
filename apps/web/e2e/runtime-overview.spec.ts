import { expect, test } from "@playwright/test";

test("repository overview keeps identity in its header and configuration on its runtime",async({page,request})=>{
  await request.post("http://127.0.0.1:50062/admin-connection?kind=ghcr");
  await page.goto("/repositories/repository:1");
  await expect(page.locator("html")).toHaveAttribute("data-hydrated","true");
  const header=page.locator("main header").filter({has:page.getByRole("heading",{name:"ayni-oss/sandbox"})});
  await expect(header.getByRole("heading",{name:"ayni-oss/sandbox"})).toBeVisible();
  await expect(header.getByRole("link",{name:"ayni-oss/sandbox"})).toHaveAttribute("href","https://github.com/ayni-oss/sandbox");
  await expect(header).toContainText("Connected");
  await expect(header).toContainText("main");
  await expect(header).not.toContainText("Ayni lock");
  await expect(page.getByText("Automatic runtime inspection",{exact:true})).toHaveCount(0);
  await expect(page.getByLabel("GHCR connection")).toHaveCount(0);
  const runtime=page.locator("article").first();
  await expect(runtime).toContainText("Ayni lock");
  await expect(runtime).toContainText("c".repeat(64));
  await expect(runtime.getByRole("button")).toHaveCount(1);
  await runtime.getByRole("button",{name:"Edit",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await dialog.getByLabel("GHCR connection").click();
  await page.getByRole("option",{name:"Admin App",exact:true}).click();
  await expect(dialog.getByLabel("Image namespace")).toHaveValue("admin-team");
  await dialog.getByLabel("Image namespace").fill("wrong");
  await dialog.getByRole("button",{name:"Save image destination",exact:true}).click();
  await expect(dialog.getByRole("alert")).toContainText("submitted request is invalid");
  await dialog.getByLabel("Image namespace").fill("admin-team");
  await request.post("http://127.0.0.1:50062/profile-version");
  await page.waitForTimeout(11000);
  await dialog.getByRole("button",{name:"Sync runtime",exact:true}).click();
  await expect(page.getByText("Runtime sync requested.",{exact:true})).toBeVisible();
  await dialog.getByRole("button",{name:"Save image destination",exact:true}).click();
  await expect(dialog.getByRole("alert")).toContainText("Close and reopen");
  await page.keyboard.press("Escape");
  await runtime.getByRole("button",{name:"Edit",exact:true}).click();
  await dialog.getByLabel("GHCR connection").click();
  await page.getByRole("option",{name:"Admin App",exact:true}).click();
  await dialog.getByRole("button",{name:"Save image destination",exact:true}).click();
  await expect(page.getByText("Runtime image destination updated.",{exact:true})).toBeVisible();
  await expect(runtime).toContainText("ghcr.io/admin-team/ayni-oss/sandbox-ayni");
  await expect(dialog.getByRole("alert")).toHaveCount(0);
  await dialog.getByRole("button",{name:"Sync runtime",exact:true}).click();
  await expect(page.getByText("Runtime sync requested.",{exact:true})).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(dialog).toBeHidden();
  await page.getByRole("button",{name:"Dismiss notification"}).click();
  await expect(page.getByText("Runtime sync requested.",{exact:true})).toHaveCount(0);
});
